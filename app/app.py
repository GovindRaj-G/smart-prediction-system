
from pathlib import Path

import joblib
import pandas as pd
import streamlit as st


# Locate project folder
BASE_DIR = Path(__file__).resolve().parent

# Load trained machine learning model
MODEL_PATH = BASE_DIR / "models" / "iris_model.pkl"
model = joblib.load(MODEL_PATH)


# Configure web application
st.set_page_config(
    page_title="Smart Prediction System",
    page_icon="🌸",
    layout="centered"
)


# Application title
st.title("🌸 Smart Prediction System")

st.write(
    "Enter the flower measurements below "
    "to predict its species using Machine Learning."
)

st.divider()


# User input section
st.subheader("Flower Measurements")

col1, col2 = st.columns(2)

with col1:
    sepal_length = st.slider(
        "Sepal Length (cm)",
        min_value=4.0,
        max_value=8.0,
        value=5.1,
        step=0.1
    )

    sepal_width = st.slider(
        "Sepal Width (cm)",
        min_value=2.0,
        max_value=4.5,
        value=3.5,
        step=0.1
    )

with col2:
    petal_length = st.slider(
        "Petal Length (cm)",
        min_value=1.0,
        max_value=7.0,
        value=1.4,
        step=0.1
    )

    petal_width = st.slider(
        "Petal Width (cm)",
        min_value=0.1,
        max_value=2.5,
        value=0.2,
        step=0.1
    )


# Predict button
if st.button("🔍 Predict Flower Species", use_container_width=True):

    # Prepare input data
    input_data = pd.DataFrame(
        [[
            sepal_length,
            sepal_width,
            petal_length,
            petal_width
        ]],
        columns=[
            "sepal length (cm)",
            "sepal width (cm)",
            "petal length (cm)",
            "petal width (cm)"
        ]
    )

    # Make prediction
    prediction = model.predict(input_data)[0]

    # Calculate probabilities
    probabilities = model.predict_proba(input_data)[0]

    # Display result
    st.success(f"Predicted Species: {prediction.upper()}")

    st.subheader("Prediction Probabilities")

    for species, probability in zip(model.classes_, probabilities):

        st.write(f"**{species.capitalize()}**")

        st.progress(float(probability))

        st.write(f"{probability * 100:.2f}%")

    st.divider()

    st.info(
        "Prediction is generated by your trained "
        "Machine Learning model."
    )


# Footer
st.caption("Built with Python, Scikit-learn and Streamlit")

model = joblib.load(MODEL_PATH)
